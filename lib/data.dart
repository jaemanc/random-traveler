double distance(double lat, double lon, Place b) {
  final r = pi / 180, dLat = (b.lat - lat) * r, dLon = (b.lon - lon) * r;
  final h =
      pow(sin(dLat / 2), 2) +
      cos(lat * r) * cos(b.lat * r) * pow(sin(dLon / 2), 2);
  return 6371 * 2 * atan2(sqrt(h), sqrt(1 - h));
}
